// Appended to src/transform.rs by generate_transform_plans.py. Compiled without
// the opus feature so the dynamic mathematical constructors generate the data.
fn main() {
    let path = std::env::args().nth(1).expect("output path");
    use std::io::Write;
    let mut file = std::io::BufWriter::new(std::fs::File::create(&path).unwrap());
    writeln!(file, "// SPDX-License-Identifier: MIT\n//! Generated by tools/generate_transform_plans.py from Snacka's own mathematics.\nuse super::{{Complex, FftPlan, MdctPlan, MdctRow, Stage}};\nconst fn c(real: u32, imaginary: u32) -> Complex {{ Complex {{ real: f32::from_bits(real), imaginary: f32::from_bits(imaginary) }} }}\ntype StageData = (usize, usize, &'static [[Complex; 4]]);\n").unwrap();
    for length in [60, 120, 240, 480] {
        let plan = FftPlan::new(length).unwrap();
        writeln!(
            file,
            "#[rustfmt::skip]\nconst FFT_{length}: &[StageData] = &["
        )
        .unwrap();
        for stage in &plan.stages {
            writeln!(file, "({}, {}, &[", stage.size, stage.radix).unwrap();
            for row in &stage.twiddles {
                write!(file, "[").unwrap();
                for value in row {
                    write!(
                        file,
                        "c(0x{:08x}, 0x{:08x}),",
                        value.real.to_bits(),
                        value.imaginary.to_bits()
                    )
                    .unwrap();
                }
                writeln!(file, "],").unwrap();
            }
            writeln!(file, "]),").unwrap();
        }
        writeln!(file, "];\n").unwrap();
    }
    for length in [120, 240, 480, 960] {
        let plan = MdctPlan::new(length, 120).unwrap();
        writeln!(
            file,
            "#[rustfmt::skip]\nconst MDCT_{length}: &[MdctRow] = &["
        )
        .unwrap();
        for row in &plan.rows {
            write!(file, "MdctRow {{ window: [").unwrap();
            for value in row.window {
                write!(file, "f32::from_bits(0x{:08x}),", value.to_bits()).unwrap();
            }
            writeln!(
                file,
                "], pre: c(0x{:08x}, 0x{:08x}), post: c(0x{:08x}, 0x{:08x}) }},",
                row.pre.real.to_bits(),
                row.pre.imaginary.to_bits(),
                row.post.real.to_bits(),
                row.post.imaginary.to_bits()
            )
            .unwrap();
        }
        writeln!(file, "];\n").unwrap();
    }
    writeln!(file, "pub(super) fn fft(length: usize) -> Option<FftPlan> {{\nlet data = match length {{ 60 => FFT_60, 120 => FFT_120, 240 => FFT_240, 480 => FFT_480, _ => return None }};\nlet stages = data.iter().map(|&(size, radix, rows)| Stage {{ size, radix, twiddles: rows.to_vec() }}).collect();\nSome(FftPlan {{ length, stages }})\n}}\n\npub(super) fn mdct(coefficients: usize, overlap: usize) -> Option<MdctPlan> {{\nif overlap != 120 {{ return None; }}\nlet rows = match coefficients {{ 120 => MDCT_120, 240 => MDCT_240, 480 => MDCT_480, 960 => MDCT_960, _ => return None }};\nSome(MdctPlan {{ coefficients, rows: rows.to_vec(), fft: fft(coefficients / 2)? }})\n}}").unwrap();
}

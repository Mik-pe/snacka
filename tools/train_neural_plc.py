"""Train finite-history int8 PLC envelopes; consumes native sufficient statistics.

Test shards are never loaded. Validation selects a quantized checkpoint, then
exported Rust must pass separate waveform/quality and invariance gates.
"""
import argparse
import copy
import hashlib
import json
import math
from pathlib import Path
import random
import time
import numpy as np
import torch
from torch import nn
import torch.nn.functional as F


class QATLinear(nn.Linear):
    def forward(self, x, qat):
        weight = self.weight
        if qat:
            scale = weight.abs().amax(dim=1, keepdim=True).clamp_min(1e-8)/127
            quantized = (weight/scale).round().clamp(-127, 127)
            weight = weight + (quantized*scale-weight).detach()
        return F.linear(x, weight, self.bias)


class Predictor(nn.Module):
    def __init__(self):
        super().__init__()
        self.layers = nn.ModuleList([QATLinear(80,64), QATLinear(64,64), QATLinear(64,16)])
        nn.init.zeros_(self.layers[2].weight)
        nn.init.zeros_(self.layers[2].bias)

    def forward(self, x, qat=True):
        for layer in self.layers[:2]:
            x = F.relu(layer(x, qat))
        return 1 + 0.5 * self.layers[2](x, qat).tanh()


def load(directory, split, device):
    paths = sorted(directory.glob(split+"-*.npz"))
    if not paths:
        raise ValueError(f"no {split} shards")
    data = {}
    for path in paths:
        with np.load(path, allow_pickle=False) as shard:
            for key in ("x","pp","pt","tt","language"):
                data.setdefault(key,[]).append(shard[key])
    data = {key: torch.as_tensor(np.concatenate(parts),device=device,dtype=torch.float32) for key,parts in data.items()}
    # v1 native shards were divided by target energy. Re-normalize their exact
    # quadratic statistics symmetrically to cap quiet-target/outlier influence.
    # This is also idempotent for new shards already using symmetric energy.
    normalizer=(data["pp"].sum(dim=1,keepdim=True)+data["tt"].sum(dim=1,keepdim=True)).clamp_min(1e-10)
    for key in ("pp","pt","tt"):
        data[key]=data[key]/normalizer
    weights = torch.zeros_like(data["language"])
    for language in (0,1):
        mask = data["language"] == language
        if mask.any(): weights[mask] = 0.5*len(mask)/mask.sum()
    data["weight"] = weights
    return data


def errors(gain, data):
    return (data["pp"]*gain.square()-2*data["pt"]*gain+data["tt"]).sum(dim=-1).clamp_min(1e-10)


@torch.no_grad()
def evaluate(model, data):
    gain = model(data["x"])
    baseline = errors(torch.ones_like(gain),data)
    current = errors(gain,data)
    result = {}
    for language,name in [(0,"en"),(1,"sv")]:
        mask = data["language"] == language
        if mask.any():
            result[name] = dict(records=int(mask.sum()),baseline_error=baseline[mask].mean().item(),
                                current_error=current[mask].mean().item(),
                                aggregate_gain_db=(10*torch.log10(baseline[mask].mean()/current[mask].mean())).item())
    result["balanced_error"] = (current*data["weight"]).mean().item()
    regularization=0.01*(gain-1).square().mean(dim=-1)
    envelope=0.1*(torch.log(data["pp"]*gain.square()+0.001)-torch.log(data["tt"]+0.001)).square().mean(dim=-1)
    result["balanced_objective"]=((current+regularization+envelope)*data["weight"]).mean().item()
    result["gain_mean"]=gain.mean().item()
    result["gain_std"]=gain.std().item()
    result["gain_lower_bound_fraction"]=(gain<0.51).float().mean().item()
    result["gain_upper_bound_fraction"]=(gain>1.49).float().mean().item()
    return result


def export(model, path, strength=1.0):
    parts=["// SPDX-License-Identifier: MIT", "// Generated by tools/train_neural_plc.py; see frozen training report.",
           "pub(crate) const ENABLED: bool = true;", f"pub(crate) const STRENGTH: f32 = {strength};"]
    for index, layer in enumerate(model.layers,1):
        w=layer.weight.detach().cpu().numpy()
        scale=np.maximum(np.abs(w).max(axis=1),1e-8)/127
        quantized=np.clip(np.rint(w/scale[:,None]),-127,127).astype(np.int8)
        rows,columns=w.shape
        parts.append(f"pub(crate) const W{index}: [[i8; {columns}]; {rows}] = [")
        parts.extend("["+", ".join(map(str,row))+"]," for row in quantized.tolist())
        parts.append("];")
        for name,values in [(f"S{index}",scale),(f"B{index}",layer.bias.detach().cpu().numpy())]:
            bits=np.asarray(values,dtype=np.float32).view(np.uint32)
            parts.append(f"pub(crate) const {name}: [f32; {len(values)}] = ["+", ".join(f"f32::from_bits(0x{int(v):08x})" for v in bits)+"];")
    path.write_text("\n".join(parts)+"\n")


def checkpoint(model, optimizer, epoch, seed):
    return dict(model=copy.deepcopy(model.state_dict()),optimizer=optimizer.state_dict(),epoch=epoch,
                rng=torch.get_rng_state(),cuda_rng=torch.cuda.get_rng_state_all() if torch.cuda.is_available() else [],
                numpy_rng=np.random.get_state(),python_rng=random.getstate(),seed=seed)


@torch.no_grad()
def export_candidate(model, data, directory, strength):
    directory.mkdir(parents=True,exist_ok=True)
    export(model,directory/"neural_plc_weights.rs",strength)
    inputs=data["x"][:32]
    # Unscaled fixture: the Rust test applies the selected correction strength.
    parity=dict(input=inputs.cpu().tolist(),gain=model(inputs).cpu().tolist())
    (directory/"parity.json").write_text(json.dumps(parity)+"\n")


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data",type=Path)
    parser.add_argument("output",type=Path)
    parser.add_argument("--epochs",type=int,default=60)
    parser.add_argument("--batch-size",type=int,default=8192)
    parser.add_argument("--seed",type=int,default=20261021,help="fresh-run seed; resume restores the checkpoint RNG state")
    parser.add_argument("--learning-rate",type=float,default=0.002)
    parser.add_argument("--schedule",choices=["constant","cosine"],default="constant")
    parser.add_argument("--minimum-lr-ratio",type=float,default=0.025)
    parser.add_argument("--resume",type=Path,help="trusted checkpoint generated by this trainer; epochs is the total target")
    parser.add_argument("--checkpoint-epochs",type=int,nargs="*",default=[])
    parser.add_argument("--export-strength",type=float,default=1.0)
    parser.add_argument("--diagnostic-interval",type=int,default=10)
    args=parser.parse_args()
    if args.epochs<11 or args.batch_size<1 or args.learning_rate<=0 or args.diagnostic_interval<1:
        parser.error("positive batch size, learning rate and diagnostic interval; at least 11 epochs required")
    if not 0<=args.minimum_lr_ratio<=1 or not 0<args.export_strength<=1:
        parser.error("minimum LR ratio must be 0..1 and export strength must be >0..1")
    args.output.mkdir(parents=True,exist_ok=True)
    dataset_hashes={path.name:hashlib.sha256(path.read_bytes()).hexdigest()
                    for path in sorted(args.data.glob("*.npz"))}
    if any(name.startswith("test") for name in dataset_hashes):
        raise ValueError("test shards must not be staged in a training directory")
    seed=args.seed
    random.seed(seed); np.random.seed(seed); torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
        torch.backends.cuda.matmul.allow_tf32 = False
    device=torch.device("cuda" if torch.cuda.is_available() else "mps" if torch.backends.mps.is_available() else "cpu")
    train=load(args.data,"train",device); validation=load(args.data,"validation",device)
    model=Predictor().to(device)
    optimizer=torch.optim.AdamW(model.parameters(),lr=args.learning_rate,weight_decay=0.0001)
    start_epoch=0; resume_hash=None
    if args.resume:
        restored=torch.load(args.resume,map_location="cpu",weights_only=False)
        model.load_state_dict(restored["model"]);optimizer.load_state_dict(restored["optimizer"])
        start_epoch=restored["epoch"];seed=restored["seed"]
        torch.set_rng_state(restored["rng"].cpu())
        if device.type=="cuda" and restored["cuda_rng"]:
            torch.cuda.set_rng_state_all([x.cpu() for x in restored["cuda_rng"]])
        np.random.set_state(restored["numpy_rng"]);random.setstate(restored["python_rng"])
        resume_hash=hashlib.sha256(args.resume.read_bytes()).hexdigest()
    if start_epoch>=args.epochs:parser.error("resume checkpoint already reached the requested epochs")
    for group in optimizer.param_groups:group["lr"]=args.learning_rate
    start=time.monotonic(); initial=evaluate(model,validation) if args.resume else None
    best=initial["balanced_objective"] if initial else float("inf")
    best_state=copy.deepcopy(model.state_dict()) if initial else None
    best_epoch=start_epoch
    if args.resume:torch.save(checkpoint(model,optimizer,start_epoch,seed),args.output/"checkpoint.pt")
    # Fixed, evenly spaced sample does not consume shuffle RNG state.
    diagnostic_indices=torch.linspace(0,len(train["x"])-1,min(32768,len(train["x"])),device=device).long()
    diagnostic={key:value[diagnostic_indices] for key,value in train.items()}
    log=[]
    print("Device",device,"training",len(train["x"]),"validation",len(validation["x"]),flush=True)
    for epoch in range(start_epoch,args.epochs):
        progress=(epoch-start_epoch)/max(1,args.epochs-start_epoch-1)
        factor=1.0 if args.schedule=="constant" else args.minimum_lr_ratio+(1-args.minimum_lr_ratio)*0.5*(1+math.cos(math.pi*progress))
        for group in optimizer.param_groups:group["lr"]=args.learning_rate*factor
        order=torch.randperm(len(train["x"]),device=device)
        model.train()
        for indices in order.split(args.batch_size):
            batch={key:value[indices] for key,value in train.items()}
            gain=model(batch["x"],qat=epoch>=10)
            error=errors(gain,batch)
            regularization=0.01*(gain-1).square().mean(dim=-1)
            envelope=0.1*(torch.log(batch["pp"]*gain.square()+0.001)-torch.log(batch["tt"]+0.001)).square().mean(dim=-1)
            loss=((error+regularization+envelope)*batch["weight"]).mean()
            optimizer.zero_grad(set_to_none=True); loss.backward()
            gradient_norm=torch.nn.utils.clip_grad_norm_(model.parameters(),1.0)
            optimizer.step()
        model.eval()
        report=evaluate(model,validation)
        entry=dict(epoch=epoch+1,seconds=time.monotonic()-start,learning_rate=optimizer.param_groups[0]["lr"],last_batch_gradient_norm=gradient_norm.item(),**report)
        if (epoch+1)%args.diagnostic_interval==0:entry["training_sample"]=evaluate(model,diagnostic)
        log.append(entry)
        if epoch>=10 and report["balanced_objective"]<best:
            best=report["balanced_objective"]; best_state=copy.deepcopy(model.state_dict());best_epoch=epoch+1
            torch.save(checkpoint(model,optimizer,epoch+1,seed),args.output/"checkpoint.pt")
        if epoch+1 in args.checkpoint_epochs:
            snapshot=args.output/f"epoch-{epoch+1:04d}"
            export_candidate(model,validation,snapshot,args.export_strength)
            torch.save(checkpoint(model,optimizer,epoch+1,seed),snapshot/"checkpoint.pt")
            (snapshot/"validation.json").write_text(json.dumps(entry,indent=2)+"\n")
        print(json.dumps(log[-1]),flush=True)
    if best_state is None: raise ValueError("no QAT checkpoint evaluated")
    torch.save(checkpoint(model,optimizer,args.epochs,seed),args.output/"last-checkpoint.pt")
    model.load_state_dict(best_state)
    export_candidate(model,validation,args.output,args.export_strength)
    report=dict(seed=seed,torch=torch.__version__,device=str(device),epochs=args.epochs,
                accelerator=torch.cuda.get_device_name(0) if device.type=="cuda" else str(device),
                batch_size=args.batch_size,training_records=len(train["x"]),validation=evaluate(model,validation),
                selected_epoch=best_epoch,start_epoch=start_epoch,resume_sha256=resume_hash,initial_validation=initial,
                learning_rate=args.learning_rate,schedule=args.schedule,minimum_lr_ratio=args.minimum_lr_ratio,
                export_strength=args.export_strength,training_diagnostic_records=len(diagnostic_indices),
                losses={"symmetric_normalized_mdct_quadratic":1.0,"gain_identity_regularization":0.01,"log_envelope":0.1},
                model="80-64-64-16 int8 weights; float activations; band gains 0.5..1.5",
                seconds=time.monotonic()-start,history=log,
                dataset_shard_sha256=dataset_hashes,
                statistics_normalization="divide pp,pt,tt by sum(pp+tt) at load",
                weights_sha256=hashlib.sha256((args.output/"neural_plc_weights.rs").read_bytes()).hexdigest())
    (args.output/"training-report.json").write_text(json.dumps(report,indent=2)+"\n")
    print("Exported",report["weights_sha256"],flush=True)


if __name__=="__main__": main()
